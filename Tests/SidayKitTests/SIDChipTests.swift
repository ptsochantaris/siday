// Regression tests for SIDChip, the Swift port of reSID. The expected values were produced by the
// C++ reSID reference harness (sidref.cc, built with -ffp-contract=off), so these catch any change
// in the port's output without needing the C++ build.

private func fnv1a<S: Sequence>(_ bytes: S) -> UInt64 where S.Element == UInt8 {
    var h: UInt64 = 1_469_598_103_934_665_603
    for b in bytes { h = (h ^ UInt64(b)) &* 1_099_511_628_211 }
    return h
}

