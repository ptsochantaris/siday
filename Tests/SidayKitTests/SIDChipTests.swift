@Test func sidMatchesReSIDOnEmbeddedTrace() {
    for (model, sampling, count, sampleDigest, readBackDigest) in SIDReference.expected {
        let (samples, readBack) = SIDReference.render(model, sampling)
        #expect(samples.count == count, "\(model) \(sampling)")
        let digest = fnv1a(samples.lazy.flatMap { [UInt8(truncatingIfNeeded: $0), UInt8(truncatingIfNeeded: $0 >> 8)] })
        #expect(digest == sampleDigest, "samples, \(model) \(sampling)")
        #expect(fnv1a(readBack) == readBackDigest, "OSC3/ENV3 read-backs, \(model) \(sampling)")
    }
}

@Test func sidTablesMatchReSID() {
    for (model, expected) in [(SIDModel.mos6581, SIDReference.tables6581), (.mos8580, SIDReference.tables8580)] {
        let sid = SIDChip(model: model, clockHz: 985_248, sampleRate: 48000, sampling: .resample)
        defer { sid.deallocate() }
        var found: [(String, Int, UInt64)] = []
        sid.withInternalTables { name, bytes in found.append((name, bytes.count, fnv1a(bytes))) }
        #expect(found.count == expected.count)
        for (a, b) in zip(found, expected) {
            #expect(a.0 == b.0 && a.1 == b.1 && a.2 == b.2, "\(model) table \(b.0)")
        }
    }
}

@Test func sidOscillatorAndEnvelopeReadBack() {
    for model in [SIDModel.mos6581, .mos8580] {
        var sid = SIDChip(model: model, clockHz: 985_248, sampleRate: 48000, sampling: .interpolate)
        defer { sid.deallocate() }
        // Voice 3: sawtooth at FREQ $1000 (the top 12 accumulator bits step once per cycle),
        // attack 0, sustain 15. Setting and clearing the test bit zeroes the accumulator.
        sid.write(0x0F, 0x10); sid.write(0x13, 0x00); sid.write(0x14, 0xF0)
        sid.write(0x12, 0x08)
        sid.clock()
        sid.write(0x12, 0x21)
        var osc: [UInt8] = []
        for _ in 0 ..< 64 {
            for _ in 0 ..< 64 { sid.clock() }
            osc.append(sid.read(0x1B))
        }
        // OSC3 is the top 8 bits: after 64*k cycles the accumulator is 64*k << 12, so OSC3 = 4*k
        // (the 8580 latches triangle/sawtooth a cycle late: 64*k - 1 gives 4*k - 1).
        let late: UInt8 = model == .mos8580 ? 1 : 0
        #expect(osc == (1 ... 64).map { UInt8(truncatingIfNeeded: 4 * $0) &- late }, "\(model)")
        // Attack rate 0 steps the envelope every 9 cycles: 64 * 64 cycles is enough to reach 255.
        let top = sid.read(0x1C)
        #expect(top == 0xFF, "\(model)")
        // Gate off with release 0: back to zero within 9 * 756 cycles (the exponential decay table).
        sid.write(0x12, 0x20)
        for _ in 0 ..< 9 * 760 { sid.clock() }
        let bottom = sid.read(0x1C)
        #expect(bottom == 0x00, "\(model)")
    }
}

@Test func sidBusValueFades() {
    for (model, ttl) in [(SIDModel.mos6581, 0x1D00), (.mos8580, 0xA2000)] {
        var sid = SIDChip(model: model, clockHz: 985_248, sampleRate: 48000, sampling: .interpolate)
        defer { sid.deallocate() }
        let buffer = UnsafeMutablePointer<Int16>.allocate(capacity: 1024)
        defer { buffer.deallocate() }
        func run(_ sid: inout SIDChip, _ count: Int) {
            var cycles = count
            while cycles > 0 { _ = sid.clock(&cycles, into: buffer, maxSamples: 1024) }
        }
        run(&sid, 10)
        sid.write(0x05, 0xA5)
        // A write-only register reads back the last value on the bus...
        let fresh = [sid.read(0x05), sid.read(0x00), sid.read(0x1F)]
        #expect(fresh == [0xA5, 0xA5, 0xA5])
        run(&sid, ttl - 1)
        let late = sid.read(0x05)
        #expect(late == 0xA5, "\(model)")
        // ...until it has faded.
        run(&sid, 1)
        let faded = sid.read(0x05)
        #expect(faded == 0x00, "\(model)")
        // The paddle registers are not modelled and read 0xff.
        let paddles = [sid.read(0x19), sid.read(0x1A)]
        #expect(paddles == [0xFF, 0xFF])
    }
}

@Test func sidClockStopsWhenTheBufferIsFull() {
    for sampling in [SIDSampling.fast, .interpolate, .resample, .resampleFastMem] {
        var sid = SIDChip(model: .mos8580, clockHz: 985_248, sampleRate: 48000, sampling: sampling)
        defer { sid.deallocate() }
        #expect(sid.samplingMethod == sampling)
        let buffer = UnsafeMutablePointer<Int16>.allocate(capacity: 64)
        defer { buffer.deallocate() }
        // One second of cycles into a 64-sample buffer: 64 samples come out and the rest stay.
        var cycles = 985_248
        let first = sid.clock(&cycles, into: buffer, maxSamples: 64)
        #expect(first == 64)
        #expect(cycles > 985_248 - 65 * 21 && cycles < 985_248 - 64 * 20)
        // Draining the rest gives 48000 samples in all, give or take the one in progress.
        var total = first
        while cycles > 0 { total += sid.clock(&cycles, into: buffer, maxSamples: 64) }
        #expect(total == 48000 || total == 47999, "\(sampling): \(total)")
    }
}

@Test func sidFallsBackToInterpolationWhenResamplingCannotWork() {
    // reSID refuses to resample when 125 * clock / rate would overfill its 16384-sample ring buffer.
    var sid = SIDChip(model: .mos6581, clockHz: 985_248, sampleRate: 4000, sampling: .resample)
    defer { sid.deallocate() }
    #expect(sid.samplingMethod == .interpolate)
    let passbandTooWide = sid.setSamplingParameters(clockHz: 985_248, sampling: .resample, sampleRate: 48000, passFrequency: 23000)
    #expect(!passbandTooWide)
    let accepted = sid.setSamplingParameters(clockHz: 985_248, sampling: .resample, sampleRate: 48000)
    #expect(accepted)
    #expect(sid.samplingMethod == .resample)
}
