@Test func reSIDfpChipsAreIndependentAndSafeToCreateConcurrently() async {
    // reSIDfp shares its dither position between all chips of a model; here every chip has its own, so a
    // chip's output is the same whatever other chips exist or do. Chips are made on several threads at once.
    let results = await withTaskGroup(of: (Int, UInt64).self) { group in
        for i in 0 ..< 8 {
            group.addTask {
                let (model, sampling, _, _, _) = ReSIDfpReference.expected[i % ReSIDfpReference.expected.count]
                return (i, fnv1a(samples: ReSIDfpReference.render(model, sampling).samples))
            }
        }
        var digests = [Int: UInt64]()
        for await (i, digest) in group { digests[i] = digest }
        return digests
    }
    for i in 0 ..< 8 {
        #expect(results[i] == ReSIDfpReference.expected[i % ReSIDfpReference.expected.count].3, "chip \(i)")
    }
}

@Test func reSIDfpOscillatorAndEnvelopeReadBack() {
    for model in [SIDModel.mos6581, .mos8580] {
        var sid = ReSIDfpChip(model: model, clockHz: 985_248, sampleRate: 48000, sampling: .decimate)
        // Voice 3: sawtooth at FREQ $1000 (the top 12 accumulator bits step once per cycle),
        // attack 0, sustain 15. Setting and clearing the test bit zeroes the accumulator.
        sid.write(0x0F, 0x10); sid.write(0x13, 0x00); sid.write(0x14, 0xF0)
        sid.write(0x12, 0x08)
        sid.clock(1)
        sid.write(0x12, 0x21)
        var osc: [UInt8] = []
        for _ in 0 ..< 64 {
            sid.clock(64)
            osc.append(sid.read(0x1B))
        }
        // OSC3 is the top 8 bits: after 64*k cycles the accumulator is 64*k << 12, so OSC3 = 4*k
        // (the 8580 latches triangle/sawtooth a cycle late: 64*k - 1 gives 4*k - 1).
        let late: UInt8 = model == .mos8580 ? 1 : 0
        #expect(osc == (1 ... 64).map { UInt8(truncatingIfNeeded: 4 * $0) &- late }, "\(model)")
        // Attack rate 0 steps the envelope every 9 cycles: 64 * 64 cycles is enough to reach 255.
        let top = sid.read(0x1C)
        #expect(top == 0xFF, "\(model)")
        // Gate off with release 0: back to zero within 9 * 756 cycles (the exponential decay table).
        sid.write(0x12, 0x20)
        sid.clock(9 * 760)
        let bottom = sid.read(0x1C)
        #expect(bottom == 0x00, "\(model)")
    }
}

