    static func parsedTrace() -> [(delta: Int, register: Int, value: Int)] {
        trace.split(whereSeparator: { $0 == "," || $0 == "\n" }).map { entry in
            let f = entry.split(separator: " ").map { Int($0)! }
            return (f[0], f[1], f[2])
