    /// Renders the trace as the harnesses do: clock, then the write or call the line stands for, then read
    /// OSC3 and ENV3. `chunk` limits how many cycles are asked for at once.
    static func render(_ sid: inout ReSIDfpChip, chunk: Int = .max, bufferSize: Int = 512, otherSIDs: Int = 0) -> (samples: [Int16], readBack: [UInt8]) {
        var samples: [Int16] = []
        var readBack: [UInt8] = []
        let buffer = UnsafeMutablePointer<Int16>.allocate(capacity: bufferSize)
        defer { buffer.deallocate() }
        for line in parsedTrace() {
            var left = line.delta
            while left > 0 {
                var cycles = min(left, chunk)
                left -= cycles
                while cycles > 0 {
                    let n = sid.clock(&cycles, into: buffer, maxSamples: bufferSize)
                    samples.append(contentsOf: UnsafeBufferPointer(start: buffer, count: n))
                }
            }
            switch line.register {
            case 33: sid.input(line.value)
            case 42: sid.setFilter6581Curve(Double(line.value) / 1000.0)
            case 43: sid.setFilter6581Range(Double(line.value) / 1000.0)
            case 44:
                sid.setFilter8580Curve(Double(line.value) / 1000.0)
                if sid.model == .mos8580 { sid.advanceDither(by: 2 * otherSIDs) }
            case 45: sid.setVoiceMuted(line.value & 3, (line.value >> 2) & 1 != 0)
            case 46: sid.setCombinedWaveforms(line.value == 2 ? .weak : line.value == 3 ? .strong : .average)
            default: sid.write(line.register, UInt8(truncatingIfNeeded: line.value))
            }
            readBack.append(sid.read(0x1B))
            readBack.append(sid.read(0x1C))
        }
        return (samples, readBack)
    }

    static func render(_ model: SIDModel, _ sampling: ReSIDfpSampling, chunk: Int = .max, bufferSize: Int = 512) -> (samples: [Int16], readBack: [UInt8]) {
        var sid = ReSIDfpChip(model: model, clockHz: 985_248, sampleRate: 48000, sampling: sampling)
        return render(&sid, chunk: chunk, bufferSize: bufferSize)
    }
