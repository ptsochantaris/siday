        run(&sid, ttl - 1)
        let held = sid.read(0x05)
        #expect(held == 0xA5, "\(model)")
        // ...until it has faded.
        sid.write(0x05, 0xA5)
        run(&sid, ttl)
        let faded = sid.read(0x05)
        #expect(faded == 0x00, "\(model)")
        // Reading a write-only register halves the time that is left.
        sid.write(0x05, 0x5A)
        run(&sid, ttl / 2)
        let untouched = sid.read(0x1F)
        sid.write(0x05, 0x5A)
        let first = sid.read(0x1F)
        run(&sid, ttl / 2)
        let second = sid.read(0x05)
        #expect([untouched, first, second] == [0x5A, 0x5A, 0x00], "\(model)")
        // The paddle registers are not modelled and read 0xff.
        let paddles = [sid.read(0x19), sid.read(0x1A)]
        #expect(paddles == [0xFF, 0xFF])
    }
}

@Test func reSIDfpClockStopsWhenTheBufferIsFull() {
    for sampling in [ReSIDfpSampling.decimate, .resample] {
        var sid = ReSIDfpChip(model: .mos8580, clockHz: 985_248, sampleRate: 48000, sampling: sampling)
        #expect(sid.samplingMethod == sampling)
        let buffer = UnsafeMutablePointer<Int16>.allocate(capacity: 64)
        defer { buffer.deallocate() }
        // One second of cycles into a 64-sample buffer: 64 samples come out and the rest stay.
        var cycles = 985_248
        let first = sid.clock(&cycles, into: buffer, maxSamples: 64)
        #expect(first == 64)
        #expect(cycles > 985_248 - 66 * 21 && cycles < 985_248 - 63 * 20)
        // Draining the rest gives a second's worth of samples. reSIDfp's resamplers step by a whole number
        // of 1024ths of a cycle, rounded down, so they run fast: 985248 * 1024 / 21018 = 48001.4 samples per
        // PAL second when decimating, and with the two passes of the sinc resampler (8334 and 2582) 48010.5.
        var total = first
        while cycles > 0 { total += sid.clock(&cycles, into: buffer, maxSamples: 64) }
        let expected = sampling == .decimate ? 48001 : 48010
        #expect(abs(total - expected) <= 1, "\(sampling): \(total)")
        // Nothing happens without room for a sample.
        var more = 100
        let none = sid.clock(&more, into: buffer, maxSamples: 0)
        #expect(none == 0 && more == 100)
    }
}

@Test func reSIDfpFallsBackToDecimationWhenResamplingCannotWork() {
    // reSIDfp's sinc resampler needs its FIR to fit a 2048-sample ring buffer (it asserts): at a PAL clock
    // that fails below about 90 Hz.
    let low = ReSIDfpChip(model: .mos6581, clockHz: 985_248, sampleRate: 40, sampling: .resample)
