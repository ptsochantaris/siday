        let sid = ReSIDfpChip(model: .mos6581, clockHz: 985_248, sampleRate: rate, sampling: .resample)
        #expect(sid.samplingMethod == .resample, "\(rate)")
    }
}

@Test func reSIDfpMutingMasksControlRegisterWrites() {
    // Peak-to-peak output of a sawtooth on voice 1, after the DC step of switching the chip on has settled.
    func swing(muted: Bool) -> Int {
        var sid = ReSIDfpChip(model: .mos8580, clockHz: 985_248, sampleRate: 48000, sampling: .decimate)
        let buffer = UnsafeMutablePointer<Int16>.allocate(capacity: 4096)
        defer { buffer.deallocate() }
        sid.setVoiceMuted(0, muted)
        sid.write(0x18, 0x0F)
        sid.write(0x00, 0x00); sid.write(0x01, 0x20); sid.write(0x05, 0x00); sid.write(0x06, 0xF0)
        sid.write(0x04, 0x21) // sawtooth, gate: muted, neither bit arrives
        var cycles = 400_000
        while cycles > 0 { _ = sid.clock(&cycles, into: buffer, maxSamples: 4096) }
        cycles = 20000
        var low = Int.max, high = Int.min
        while cycles > 0 {
            let n = sid.clock(&cycles, into: buffer, maxSamples: 4096)
            for i in 0 ..< n {
                low = min(low, Int(buffer[i]))
                high = max(high, Int(buffer[i]))
            }
        }
        return high - low
    }
    let audible = swing(muted: false), silent = swing(muted: true)
    #expect(audible > 4000, "\(audible)")
    #expect(silent < 200, "\(silent)")
}
