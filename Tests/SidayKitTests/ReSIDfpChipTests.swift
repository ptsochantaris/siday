// C++ reSIDfp reference harness (sidfpref.cc: libsidplayfp 2.16.1's reSIDfp built with -ffp-contract=off
// and its table-building threads run one after the other), so these catch any change in the port's
// output without needing the C++ build.

private func fnv1a<S: Sequence>(_ bytes: S) -> UInt64 where S.Element == UInt8 {
    var h: UInt64 = 1_469_598_103_934_665_603
    for b in bytes { h = (h ^ UInt64(b)) &* 1_099_511_628_211 }
    return h
}

private func fnv1a(samples: [Int16]) -> UInt64 {
    fnv1a(samples.lazy.flatMap { [UInt8(truncatingIfNeeded: $0), UInt8(truncatingIfNeeded: $0 >> 8)] })
}

