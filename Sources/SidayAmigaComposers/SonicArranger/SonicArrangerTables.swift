    /// A byte of the two tables as they lie in Wanted Team's player, the vibrato's straight after the
    /// periods', from the first byte of the periods': what is before them (the player's code) and
    /// after them (the end of its code) is read here as nought.
    static func byte(_ at: Int) -> UInt8 {
        if at >= 0, at < 220 {
            let period = periods[at >> 1]
            return UInt8(truncatingIfNeeded: at & 1 == 0 ? period >> 8 : period)
        }
        if at >= 220, at < 476 { return vibrato[at - 220] }
        return 0
    }
