    /// Where a row's note nought is in `periods`.
    static let noteNought = 7

    /// Mugician II's table of each voice's sample at each volume (`lbL011FB6`, made by its player's
    /// `lbC010B32`): for a volume of 0 to 63 and a sample byte, the sample times the volume over 63,
    /// rounded towards nought, and one less for a sample below nought at a volume that is neither
    /// nought nor 63; with $80 added, so that four of them come to no more than 1,020, nought being 512.
    static let volumes: [UInt8] = {
        var table = [UInt8](repeating: 0, count: 64 * 256)
        for volume in 0 ..< 64 {
            for index in 0 ..< 256 {
                let sample = index < 128 ? index : index - 256
                var value = UInt8(truncatingIfNeeded: sample * volume / 63) &+ 0x80
                if volume != 0, volume != 63, index >= 0x80 { value &-= 1 }
                table[volume * 256 + index] = value
            }
        }
        return table
    }()
